"""
============================================================
U-Net 및 Attention U-Net 모델 구현
============================================================

1. 기존 U-Net 모델 구성
------------------------------------------------------------
- 모델 구조: U-Net
- Encoder: ResNet34
- 사전 학습 가중치: ImageNet
- 입력 채널: 3
- 출력 채널: 1

2. 백본 선정 이유
------------------------------------------------------------
5-Fold Cross Validation을 통해 네 가지 백본의 성능을 비교하였다.

ResNet34는 Dice 0.9745로 가장 높은 성능을 기록했으며,
ResNet50과 유사한 분할 정확도를 보이면서 처리 시간은 더 짧았다.

이를 바탕으로 정확도와 처리 속도의 균형을 고려하여
기본 U-Net의 Encoder로 ResNet34를 선정하였다.

3. 백본별 5-Fold 평균 실험 결과
------------------------------------------------------------
Backbone          IoU      Dice     Time(ms)   HC_MAE(mm)
------------------------------------------------------------
ResNet18          0.9532   0.9742     9.67        2.00
ResNet34          0.9537   0.9745    12.31        1.98
ResNet50          0.9537   0.9740    15.58        1.94
EfficientNet-B0   0.9529   0.9741    16.66        2.12
------------------------------------------------------------

4. Attention U-Net 구현 목적
------------------------------------------------------------
기존 U-Net의 Skip Connection에 Attention Gate를 적용하여
분할 대상인 태아 머리 영역의 특징을 강조하고
불필요한 배경 정보를 억제하는 모델을 구현하였다.

[주요 구성]
- Encoder: ResNet34
- Attention Gate: 중요한 공간 영역 선택
- Decoder: 특징맵 복원 및 결합
- Segmentation Head: 최종 분할 마스크 생성

5. 평가 지표
------------------------------------------------------------
- IoU: 예측 마스크와 정답 마스크의 겹치는 정도
- Dice: 예측 마스크와 정답 마스크의 유사도
- Time: 이미지 한 장의 평균 처리 시간
- HC_MAE: 머리둘레 평균 절대 오차(mm)

6. 참고 사항
------------------------------------------------------------
- 백본 비교 결과는 타원 보정 후 평가한 값이다.
- 실험 결과는 5-Fold 평균을 기준으로 한다.
- Attention U-Net은 기존 U-Net과 성능을 비교하기 위한
  추가 실험 모델이다.
============================================================
"""

import segmentation_models_pytorch as smp


def build_unet(pretrained=True):
    """
    ResNet34 Encoder 기반 U-Net 모델 생성

    Args:
        pretrained (bool):
            ImageNet 사전 학습 가중치 사용 여부

    Returns:
        U-Net 모델
    """

    model = smp.Unet(
        encoder_name="resnet34",
        encoder_weights="imagenet" if pretrained else None,
        in_channels=3,
        classes=1,
        activation=None
    )

    return model
